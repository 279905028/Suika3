'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
// Quoting is deliberately separate from shell escaping. Never interpolate this into commands.
function quoted(s){assert(typeof s==='string'&&!/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(s),'不支持的控制字符');return JSON.stringify(s);}
function ray(x){
  if(typeof x==='string')return quoted(x);
  if(typeof x==='number'||typeof x==='boolean')return String(x);
  if(Array.isArray(x))return '['+x.map(ray).join(', ')+']';
  assert(x&&typeof x==='object','Ray数据不能为null');
  return '{'+Object.entries(x).map(([k,v])=>{assert(/^[a-zA-Z_][a-zA-Z_0-9]*$/.test(k),'非法Ray键');return k+': '+ray(v);}).join(', ')+'}';
}
function emit(ir){
  const R=ir.contract, novel=['# Generated by SUI-C. Do not edit.','[label name="SC_ENTRY"]',`[goto name=${quoted(ir.entry)}]`], mappings={};
  const code=[`// Generated SUI-C module; build ${ir.buildId}`,`var sc_build_id = ${quoted(ir.buildId)};`,'var sc_choices = {};','var sc_ops = {};','var sc_entries = {};','var sc_routes = {};',`var sc_score_rules = ${ray(R.piaoRelation.choices.map(c=>({id:c.id,a:c.effects.A,b:c.effects.B})))};`,`var sc_ep_rules = ${ray(R.epilogues.rules.map(r=>({relation:r.relation,endings:r.endings,target:r.target?.anchor||'',file:r.target?.file||'',event:r.requiresEvent||''})))};`,`var sc_initial = ${R.piaoRelation.initialScore};`,`var sc_threshold = ${R.piaoRelation.freeze.highAtLeast};`,`var sc_route_choice = ${quoted(R.storyEntry.routeChoice)};`,`var sc_hidden = ${quoted(R.hiddenEntry.routeId)};`,`var sc_meeting_event = ${quoted(R.hiddenEntry.readEvent)};`,`var sc_pregnancy_event = ${quoted(R.day36.eventId)};`,`var sc_meeting_neutral = ${quoted(R.hiddenEntry.neutralChoice)};`,`var sc_hq_required = ${ray(Object.entries(R.hiddenEntry.choiceRequirements).map(([id,value])=>({id,value})))};`,'func sc_install() {'];
  for(const c of Object.values(ir.choices)){
    const owner=R.routes.find(r=>r.file===c.source.file);
    code.push(`    sc_choices[${quoted(c.id)}] = ${ray({values:c.options.map(o=>o.value),owner:owner?.id||'',low:owner?.id==='piao'&&c.id===owner.lowPathChoice})};`);
  }
  for(const r of R.routes){const data={keys:r.keyChoices,aa:r.outcomes.AA,ab:r.outcomes.AB,ba:r.outcomes.BA,bb:r.outcomes.BB,lowChoice:r.lowPathChoice||'',lowA:r.lowPathOutcomes?.A||'',lowB:r.lowPathOutcomes?.B||'',returnTo:R.day36.calls.find(c=>c.routeId===r.id)?.returnAnchor||''};code.push(`    sc_routes[${quoted(r.id)}] = ${ray(data)};`);code.push(`    sc_entries[${quoted(r.id)}] = ${quoted(ir.entries[r.file])};`);}
  for(const n of ir.nodes){
    const start=novel.length+1;novel.push(`[label name=${quoted(n.id)}]`);
    if(n.op==='text'){
      novel.push(`[sc_at id=${quoted(n.id)}]`,`[text text=${quoted(n.text)}]`,`[goto name=${quoted(n.next)}]`);
    } else if(n.op==='choice'){
      const c=ir.choices[n.choice];novel.push(`[sc_at id=${quoted(n.id)}]`,`[text text=${quoted(c.question)}]`,`[sc_choose id=${quoted(n.choice)}]`);
      const sets=n.choice===R.storyEntry.routeChoice?[['all',c.options],['locked',c.options.filter(o=>o.value!==R.hiddenEntry.routeId)]]:[['all',c.options]];
      for(const[suffix,opts]of sets)novel.push(`[label name=${quoted(n.id+'__'+suffix)}]`,'[choose name="sc_input" '+opts.map((o,i)=>`text${i+1}=${quoted(o.text)} value${i+1}=${quoted(o.value)}`).join(' ')+']',`[sc_commit id=${quoted(n.id)} next=${quoted(n.next)}]`);
    } else {
      const op={op:n.op,next:n.next||''};
      for(const k of ['condition','otherwise','event','ending','target','returnTo','route'])if(n[k]!==undefined)op[k]=n[k];
      if(n.op==='finish'){
        const i=R.storyEntry.common.indexOf(n.file);op.kind=i>=0?'common':n.file===R.storyEntry.routeEntry?'route':n.file===R.day36.sharedSource.file?'invalid-return':'done';
        if(i>=0)op.next=ir.entries[R.storyEntry.common[i+1]||R.storyEntry.routeEntry];
      }
      const rayLine=code.length+1;code.push(`    sc_ops[${quoted(n.id)}] = ${ray(op)};`);
      novel.push(`[sc_step id=${quoted(n.id)}]`);mappings[n.id]={rayLine};
    }
    mappings[n.id]={...mappings[n.id],source:n.source,op:n.op,novelStart:start,novelEnd:novel.length,...(n.op==='text'?{paragraph:n.paragraph,offset:n.offset,graphemes:Array.from(new Intl.Segmenter('zh',{granularity:'grapheme'}).segment(n.text)).length}:{})};
  }
  code.push('}');
  // This bundled VM has a bounded per-function constant/register budget.
  // Keep independent metadata registration functions small.
  const begin=code.indexOf('func sc_install() {');
  const registrations=code.splice(begin+1,code.length-begin-2);
  const batches=[];
  for(let i=0;i<registrations.length;i+=12)batches.push(registrations.slice(i,i+12));
  code.splice(begin,2,'func sc_install() {',...batches.map((_,i)=>`    sc_install_${i}();`),'}');
  for(const[batch,lines]of batches.entries())code.push(`func sc_install_${batch}() {`,...lines,'}');
  for(const[id,m]of Object.entries(mappings))if(m.rayLine)m.rayLine=code.findIndex(line=>line.startsWith(`    sc_ops[${quoted(id)}] =`))+1;
  code.push(fs.readFileSync(path.join(__dirname,'runtime.ray'),'utf8'));
  novel.push('[label name="SC_DONE"]','[sc_halt]','[label name="SC_ERROR"]','[text text="编译运行状态错误。请保留当前记录并查看错误日志。"]','[sc_halt]');
  return {'story.novel':novel.join('\n')+'\n','story.ray':code.join('\n')+'\n','source-map.json':JSON.stringify({version:1,buildId:ir.buildId,units:mappings,omitted:ir.omitted},null,2)+'\n'};
}
module.exports={emit,quoted};
